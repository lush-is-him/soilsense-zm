"""A short Tonga follow-up form: only the lines with no Tonga yet, plus lines to fix.

    python scripts/make_followup_form.py

Writes docs/translations/followup_form.gs (paste into script.google.com, run
createFollowupForm) and docs/translations/followup_keys.json. Read the answers
back with:

    python scripts/i18n_form_import.py RESPONSES.csv --lang toi --keys docs/translations/followup_keys.json --alias TOI-1

N questions: new English lines added after the first form (Nov 2026).
F questions: earlier Tonga lines in which the phone's autocorrect left English
words (optional to answer; an empty answer keeps the current line).
"""

import json
import re
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "translations"
AUTOCORRECT = re.compile(r"\b(misunderstanding|meningitis|available|excited|teaching|business|muscle|Ingatestone|"
                         r"Kuala|mucilage|Chapman|mobile|izaak)\b", re.IGNORECASE)


def build(lang="toi"):
    english = yaml.safe_load((ROOT / "i18n" / "en.yaml").read_text(encoding="utf-8"))
    current = yaml.safe_load((ROOT / "i18n" / f"{lang}.yaml").read_text(encoding="utf-8")) or {}
    new = [k for k in english if k not in current]
    fix = [k for k, v in current.items() if AUTOCORRECT.search(v["text"])]
    keys = {"N": new, "F": fix}
    data = {
        "new": [[f"N{i}", english[k]["text"]] for i, k in enumerate(new, 1)],
        "fix": [[f"F{i}", english[k]["text"], current[k]["text"]] for i, k in enumerate(fix, 1)],
    }
    return keys, data


SCRIPT = r"""/**
 * SoilSense ZM: short Tonga follow-up form. Generated by scripts/make_followup_form.py.
 * script.google.com > New project > paste > Save > choose createFollowupForm > Run.
 * The Execution log prints the link to send and the responses spreadsheet.
 */

var DATA = __DATA__;

function createFollowupForm() {
  var form = FormApp.create('SoilSense ZM: Tonga, a few more lines');
  form.setDescription(
    'Thank you again for translating SoilSense ZM. The app now speaks more plainly to farmers, so there are ' +
    DATA.new.length + ' new short lines, plus a few earlier lines where the phone changed Tonga words into English ones.\n\n' +
    '- Keep anything in curly brackets exactly as it is: {crop}, {items}, {crops}. The app fills them in.\n' +
    '- Keep numbers the same.\n' +
    '- Please turn off autocorrect on your phone keyboard first.\n' +
    'About 15 minutes.');
  form.setCollectEmail(false);
  form.setProgressBar(true);
  form.setConfirmationMessage('Thank you! These lines will be added to SoilSense ZM.');
  form.addTextItem().setTitle('Your name or initials').setRequired(true);

  form.addPageBreakItem().setTitle('New lines')
      .setHelpText('Write each line in Tonga, in simple words a farmer would use.');
  DATA.new.forEach(function (s) {
    var item = form.addParagraphTextItem().setTitle(s[0] + '. ' + s[1]);
    if (s[1].indexOf('{') >= 0) item.setHelpText('Keep the words in {curly brackets} exactly as they are.');
  });

  if (DATA.fix.length) {
    form.addPageBreakItem().setTitle('Lines to fix (optional)')
        .setHelpText('The phone changed some Tonga words into English ones. Write the corrected Tonga, ' +
                     'or leave it empty to keep the line as it is.');
    DATA.fix.forEach(function (s) {
      form.addParagraphTextItem().setTitle(s[0] + '. ' + s[1])
          .setHelpText('Now: ' + s[2] + (s[1].indexOf('{') >= 0 ? '\nPlease include {crop} where the crop name goes.' : ''));
    });
  }

  var sheet = SpreadsheetApp.create('SoilSense ZM: Tonga follow-up (responses)');
  form.setDestination(FormApp.DestinationType.SPREADSHEET, sheet.getId());
  Logger.log('SEND THIS LINK: ' + form.shortenFormUrl(form.getPublishedUrl()));
  Logger.log('Responses spreadsheet: ' + sheet.getUrl());
}
"""


def main():
    keys, data = build()
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "followup_form.gs").write_text(SCRIPT.replace("__DATA__", json.dumps(data, ensure_ascii=False, indent=1)),
                                          encoding="utf-8")
    (OUT / "followup_keys.json").write_text(json.dumps(keys, indent=1), encoding="utf-8")
    print(f"Wrote followup_form.gs: {len(keys['N'])} new lines, {len(keys['F'])} lines to fix")


if __name__ == "__main__":
    main()
