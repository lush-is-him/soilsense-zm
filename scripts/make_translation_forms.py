"""Build the Google Apps Script that creates the Nyanja and Tonga translation forms.

    python scripts/make_translation_forms.py

Writes docs/translations/translation_forms.gs (paste into script.google.com)
and docs/translations/form_keys.json (which question is which string, used
by scripts/i18n_form_import.py to read the answers back).
"""

import json
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
I18N = ROOT / "i18n"
OUT = ROOT / "docs" / "translations"
CHUNK = 12          # sentences per form page, so each page fits on a phone screen

GLOSSARY = [
    "lime (agricultural lime for acid soil)", "acid soil / sour soil", "soil test", "manure",
    "fertiliser", "basal fertiliser (put in at planting)", "top dressing (fertiliser added later)",
    "planting station / planting basin", "seed variety", "lima (area unit)", "extension officer",
    "soil lab", "texture-by-feel (rubbing soil between fingers)", "sandy soil", "loamy soil",
    "clay soil", "waterlogged", "pH",
]
LANGS = {"ny": "Nyanja", "toi": "Tonga"}


def load(code):
    return yaml.safe_load((I18N / f"{code}.yaml").read_text(encoding="utf-8")) or {}


def build():
    english = load("en")
    crops = [k for k in english if k.startswith("crop.") and "{" not in english[k]["text"]]
    sentences = [k for k in english if k not in crops]
    keys = {"W": GLOSSARY, "C": crops, "S": sentences}
    forms = {}
    for code, name in LANGS.items():
        drafts = load(code)
        def draft(key):
            entry = drafts.get(key)
            return entry["text"] if entry else ""
        forms[code] = {
            "name": name,
            "glossary": [[f"W{i}", w] for i, w in enumerate(GLOSSARY, 1)],
            "crops": [[f"C{i}", english[k]["text"], draft(k)] for i, k in enumerate(crops, 1)],
            "sentences": [[f"S{i}", english[k]["text"], draft(k)] for i, k in enumerate(sentences, 1)],
        }
    return keys, forms


SCRIPT = r"""/**
 * SoilSense ZM: translation forms (Nyanja and Tonga) as Google Forms.
 * Generated by scripts/make_translation_forms.py. Do not edit by hand.
 *
 * How to use (once, about 5 minutes):
 *   1. Go to https://script.google.com and click "New project".
 *   2. Delete the empty code, paste this whole file, click Save.
 *   3. Choose "createBothForms" in the function box at the top and click Run.
 *   4. Allow the permissions (if Google says the app is not verified:
 *      Advanced > Go to project. It is your own script).
 *   5. Open "Execution log" at the bottom: it prints one link per language
 *      to send to the translators, and the response spreadsheets.
 */

var DATA = __DATA__;
var CHUNK = __CHUNK__;

function createBothForms() {
  createForm_('ny');
  createForm_('toi');
}

function createForm_(code) {
  var d = DATA[code];
  var hasDraft = d.sentences.some(function (s) { return s[2]; });
  var form = FormApp.create('SoilSense ZM: ' + d.name + ' translation');
  form.setDescription(
    'SoilSense ZM is a student project (ZCAS University) that gives smallholder farmers in Kafue ' +
    'District advice about soil acidity, lime and crops, on a phone and by SMS. Please help put the ' +
    'advice into ' + d.name + ' so farmers can understand it.\n\n' +
    '- Use simple words a farmer would use. Short and clear is better than word-for-word.\n' +
    '- Keep anything in curly brackets exactly as it is, for example {crop}. The system puts the crop name there.\n' +
    '- Keep the numbers the same.\n' +
    '- If a word has no good ' + d.name + ' word, keep the English word.\n' +
    '- You can skip any question you are unsure about.\n\n' +
    'Your progress is not saved if you close the page, so please answer in one sitting (about 30 to 45 minutes).');
  form.setCollectEmail(false);
  form.setProgressBar(true);
  form.setConfirmationMessage('Thank you! Your translations will be checked and added to SoilSense ZM.');

  form.addPageBreakItem().setTitle('About you');
  form.addTextItem().setTitle('Your name or initials').setRequired(true);
  form.addMultipleChoiceItem().setTitle('May we thank you by name in the dissertation?')
      .setChoiceValues(['Yes', 'No, keep me anonymous']).setRequired(true);
  form.addMultipleChoiceItem().setTitle('Is ' + d.name + ' your first language?')
      .setChoiceValues(['Yes', 'No']).setRequired(true);
  form.addTextItem().setTitle('Where did you grow up? (district or area)');

  form.addPageBreakItem().setTitle('Key words')
      .setHelpText('The ' + d.name + ' word a farmer would use for each of these.');
  d.glossary.forEach(function (w) { form.addTextItem().setTitle(w[0] + '. ' + w[1]); });

  form.addPageBreakItem().setTitle('Crop names');
  d.crops.forEach(function (c) {
    var item = form.addTextItem().setTitle(c[0] + '. ' + c[1]);
    if (c[2]) item.setHelpText('Draft: ' + c[2] + '   (write OK if it is right)');
  });

  for (var start = 0; start < d.sentences.length; start += CHUNK) {
    var part = d.sentences.slice(start, start + CHUNK);
    form.addPageBreakItem()
        .setTitle('Advice sentences ' + (start + 1) + ' to ' + (start + part.length) + ' of ' + d.sentences.length)
        .setHelpText(hasDraft
          ? 'Each sentence has a computer draft below it. Write OK if the draft is right, or write the correct ' + d.name + '.'
          : 'Write each sentence in ' + d.name + '.');
    part.forEach(function (s) {
      var help = [];
      if (s[2]) help.push('Draft: ' + s[2] + '   (write OK if it is right)');
      if (s[1].indexOf('{') >= 0) help.push('Keep {crop} exactly as it is.');
      var item = form.addParagraphTextItem().setTitle(s[0] + '. ' + s[1]);
      if (help.length) item.setHelpText(help.join('\n'));
    });
  }

  form.addPageBreakItem().setTitle('Anything else');
  form.addParagraphTextItem().setTitle('Comments: words that were hard to translate, or advice that would confuse farmers');

  var sheet = SpreadsheetApp.create('SoilSense ZM: ' + d.name + ' translation (responses)');
  form.setDestination(FormApp.DestinationType.SPREADSHEET, sheet.getId());
  Logger.log(d.name.toUpperCase() + ' - SEND THIS LINK: ' + form.shortenFormUrl(form.getPublishedUrl()));
  Logger.log(d.name + ' responses spreadsheet: ' + sheet.getUrl());
}
"""


def main():
    keys, forms = build()
    OUT.mkdir(parents=True, exist_ok=True)
    script = SCRIPT.replace("__DATA__", json.dumps(forms, ensure_ascii=False, indent=1)).replace("__CHUNK__", str(CHUNK))
    (OUT / "translation_forms.gs").write_text(script, encoding="utf-8")
    (OUT / "form_keys.json").write_text(json.dumps(keys, indent=1), encoding="utf-8")
    print(f"Wrote {OUT / 'translation_forms.gs'} ({len(keys['W'])} words, {len(keys['C'])} crops, "
          f"{len(keys['S'])} sentences per language) and form_keys.json")


if __name__ == "__main__":
    main()
